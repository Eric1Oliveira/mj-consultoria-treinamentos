const DICIONARIOS = { 'pt-BR': pt, en, es };

let atual = IDIOMA_PADRAO;

export function idiomaAtual() {
    return atual;
}

export function definirIdioma(codigo) {
    atual = DICIONARIOS[codigo] ? codigo : IDIOMA_PADRAO;
    document.documentElement.lang = atual;
    return atual;
}

/** Idioma inicial: o salvo, senão o padrão (pt-BR) — não segue o navegador, por decisão do projeto. */
export function idiomaValido(codigo) {
    return Boolean(DICIONARIOS[codigo]);
}

function buscar(dicionario, chave) {
    return chave.split('.').reduce((no, parte) => (no == null ? undefined : no[parte]), dicionario);
}

/**
 * t('painel.ola', { nome: 'Ana' }) → 'Olá, Ana'.
 * Chave ausente no idioma atual cai no português; ausente nos dois, devolve a própria chave.
 * Os marcadores (:nome) são trocados de uma vez, então :n não atrapalha :nome.
 */
export function t(chave, params = {}) {
    const valor = buscar(DICIONARIOS[atual], chave) ?? buscar(pt, chave);
    if (valor === undefined) return chave;
    if (typeof valor !== 'string') return valor; // listas e grupos (ex.: gamificacao.niveis)
    return valor.replace(/:([a-zA-Z]+)/g, (marcador, nome) => (nome in params ? String(params[nome]) : marcador));
}

/** Todas as chaves de um dicionário (usado na verificação de paridade). */
export function chaves(codigo) {
    const lista = [];
    const andar = (no, prefixo) => {
        for (const [k, v] of Object.entries(no)) {
            const caminho = prefixo ? `${prefixo}.${k}` : k;
            if (v && typeof v === 'object' && !Array.isArray(v)) andar(v, caminho);
            else lista.push(caminho);
        }
    };
    andar(DICIONARIOS[codigo], '');
    return lista;
}

